import { test,expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test('administrator login, real cohort, filters, accessibility, logout',async({page})=>{
 const username=process.env.ADMIN_USERNAME,password=process.env.ADMIN_PASSWORD;
 if(!username||!password)throw new Error('Set ephemeral administrator credentials for browser verification');
 await page.goto('/admin');
 await expect(page.getByRole('heading',{level:1})).toHaveText('관리자 로그인');
 await expect(page.getByRole('button',{name:'로그인'})).toBeVisible();
 expect((await page.request.get('/api/admin/funnel')).status()).toBe(401);
 expect((await new AxeBuilder({page}).analyze()).violations.filter(v=>v.impact==='serious'||v.impact==='critical')).toEqual([]);
 const csrf=await (await page.request.get('/api/csrf')).json();
 const start=await page.request.post('/api/sessions',{headers:{[csrf.headerName]:csrf.token},data:{scenarioId:'boram-cafe',version:1,uiVariant:'standard'}});
 expect(start.status()).toBe(201);const session=await start.json();
 const submitted=await page.request.post('/api/sessions/'+session.id+'/submit',{headers:{[csrf.headerName]:csrf.token},data:{order:[{menuId:'americano',optionIds:['ice'],packing:'TAKE_OUT',quantity:2}],payment:'CARD',clientActiveMs:1000}});
 expect(submitted.status()).toBe(200);
 const events=['MISSION','MENU','CART','PAYMENT'].map((to,i)=>({eventId:crypto.randomUUID(),sessionId:session.id,sequence:i+1,eventType:'STATE_TRANSITION',scenarioId:'boram-cafe',scenarioVersion:1,clientTimestamp:new Date().toISOString(),uiVariant:'standard',payload:{from:i===0?'STARTING':['MISSION','MENU','CART'][i-1],to}}));
 expect((await page.request.post('/api/sessions/'+session.id+'/events',{headers:{[csrf.headerName]:csrf.token},data:{events}})).status()).toBe(200);
 await page.getByLabel('관리자 아이디').fill(username);
 await page.getByLabel('비밀번호').fill(crypto.randomUUID());
 await page.getByRole('button',{name:'로그인'}).click();await expect(page.getByRole('alert')).toContainText('로그인 정보를');
 await page.getByLabel('관리자 아이디').fill(username);await page.getByLabel('비밀번호').fill(password);
 await page.getByRole('button',{name:'로그인'}).click();
 await expect(page.getByRole('heading',{level:1})).toHaveText('학습 분석 대시보드');
 await expect(page.getByRole('table',{name:'단계별 도달 및 다음 단계 미도달'})).toBeVisible();
 expect((await page.request.get('/api/sessions/'+session.id)).status()).toBe(200);
 const report=await (await page.request.get('/api/admin/funnel?scenarioId=boram-cafe&version=1')).json();
 expect(report.metrics.completed).toBeGreaterThanOrEqual(1);expect(report.funnel[5].reached).toBeGreaterThanOrEqual(1);
 await page.getByLabel('시나리오',{exact:true}).selectOption('boram-cafe:1');
 await page.getByRole('button',{name:'통계 조회'}).click();
 await expect(page.getByRole('table',{name:'단계별 도달 및 다음 단계 미도달'})).toBeVisible();
 await page.getByRole('button',{name:'고대비 모드'}).focus();await page.keyboard.press('Enter');
 await expect(page.getByRole('button',{name:'고대비 모드'})).toHaveAttribute('aria-pressed','true');
 expect((await new AxeBuilder({page}).analyze()).violations.filter(v=>v.impact==='serious'||v.impact==='critical')).toEqual([]);
 const sizes=await page.locator('button,input,select').evaluateAll(nodes=>nodes.filter(n=>n.getClientRects().length>0).map(n=>({w:n.getBoundingClientRect().width,h:n.getBoundingClientRect().height})));
 expect(sizes.every(r=>r.w>=48&&r.h>=48)).toBe(true);
 await page.getByRole('button',{name:'고대비 모드'}).click();
 await page.screenshot({path:test.info().outputPath('admin-dashboard.jpg'),type:'jpeg',quality:72,fullPage:true});
 await test.info().attach('admin-dashboard',{path:test.info().outputPath('admin-dashboard.jpg'),contentType:'image/jpeg'});
 await page.getByLabel('시작일 (UTC)').fill('2001-01-01');await page.getByLabel('종료일 (제외)').fill('2001-01-02');
 await page.getByRole('button',{name:'통계 조회'}).click();await expect(page.getByText('해당 조건의 학습 데이터가 없습니다.',{exact:false})).toBeVisible();
 await page.getByRole('button',{name:'로그아웃'}).click();
 await expect(page.getByRole('heading',{level:1})).toHaveText('관리자 로그인');
 expect((await page.request.get('/api/admin/funnel')).status()).toBe(401);
 expect((await page.request.get('/api/sessions/'+session.id)).status()).toBe(200);
 console.log('ADMIN_UI_PASS');
});
